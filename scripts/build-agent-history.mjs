// Bundle the fixture with the current native calculation code for workerd's
// contained JavaScript-only history boundary. Never imported by the product.
import {build} from 'esbuild'
await build({entryPoints:['tests/agent-learning-history.ts'],outfile:'tests/agent-learning-history.mjs',bundle:true,format:'esm',platform:'node',target:'es2022',banner:{js:'// Generated by node scripts/build-agent-history.mjs from native demand calculations.'},plugins:[{
 name:'native-calculations-only',setup(builder) {
  // These calculations are pure. Drop unused service initialization while
  // retaining every function and constant reached by the native computation.
  builder.onResolve({filter:/^\./},async args=>{
   if(args.pluginData?.resolved)return
   const resolved=await builder.resolve(args.path,{resolveDir:args.resolveDir,kind:args.kind,pluginData:{resolved:true}})
   return {...resolved,sideEffects:false}
  })
 }
}]})
